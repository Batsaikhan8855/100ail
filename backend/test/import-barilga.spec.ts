import { cleanName, SERVICE_NAME } from "../prisma/import-barilga";

describe("cleanName", () => {
  it("нэрнээс утасны дугаарыг хасна", () => {
    expect(cleanName("Ноц Бетон Зуурмаг-88467137")).toBe("Ноц Бетон Зуурмаг");
    expect(cleanName("Бетон зуурмагийн үнэ хямдарлаа-88467137 77440000")).toBe(
      "Бетон зуурмагийн үнэ хямдарлаа",
    );
    expect(cleanName("Beton zuurmg niiluulne- 88467137,77440000")).toBe(
      "Beton zuurmg niiluulne",
    );
  });

  it("утасны дүрсийг хасна", () => {
    expect(cleanName("Бетон зуурмаг нийлүүлнэ-☎️88467137")).toBe(
      "Бетон зуурмаг нийлүүлнэ",
    );
  });

  it("хэмжээ заасан /…/ хаалтыг хэвээр үлдээнэ", () => {
    expect(cleanName("Pyramid Mortar-21 /Гадна хар замаск/")).toBe(
      "Pyramid Mortar-21 /Гадна хар замаск/",
    );
    expect(cleanName("Дам нурууны хавчаар /резватай, түгжээтэй/")).toBe(
      "Дам нурууны хавчаар /резватай, түгжээтэй/",
    );
  });

  it("бүтээгдэхүүний загварын дугаарт хүрэхгүй", () => {
    // 8 оронтой биш тул дугаар гэж үзэхгүй
    expect(cleanName("Камкабель ПВЗ 1х1,5")).toBe("Камкабель ПВЗ 1х1,5");
    expect(cleanName("S1800W /30-35мкв/ халаагуур")).toBe(
      "S1800W /30-35мкв/ халаагуур",
    );
  });

  it("нэр бүхэлдээ дугаар байвал эхийг нь үлдээнэ", () => {
    expect(cleanName("88467137")).toBe("88467137");
  });
});

describe("SERVICE_NAME", () => {
  it("материал биш үйлчилгээний зарыг таньдаг", () => {
    for (const name of [
      "Солонгос руу бизнесийн гуйвуулга",
      "Барилгын зураг төсөл хийнэ.",
      "Вэб сайт хийх үйлчилгээ",
      "Интерьер зураг төсөл",
    ]) {
      expect(SERVICE_NAME.test(name)).toBe(true);
    }
  });

  it("бодит барааны нэрэнд санамсаргүй таарахгүй", () => {
    for (const name of [
      "Телевиз тавиур",
      "Обой, хуулга",
      "Өрлөгийн улаан тоосго",
      "Герман улсын CLASSEN ламинатан шал",
      "Дулаан тусгаарлах системийн бэхэлгээний тор",
      "Бетон зуурмаг",
    ]) {
      expect(SERVICE_NAME.test(name)).toBe(false);
    }
  });
});
