#!/bin/sh
# Контейнер эхлэх үрлэл.
#
# Схемийн тохируулга энд хийгдэнэ — хостингоос үл хамааран нэг ижил
# ажиллахын тулд (Railway-ийн `preDeploy` эсвэл docker-compose хоёуланд).
# Контейнер дахин эхлэх бүрд энэ скрипт ажилладаг тул сервер асахаас
# өмнөх ажлыг дор хаяж багасгасан:
#
#   * `sync-schema` нь схемийн хэшийг сантай тулгаад, өөрчлөгдөөгүй бол
#     шууд буцна (хагас секунд). Зөвхөн схем солигдсон deploy дээр
#     `db push` ажиллана — өмнө нь эхлэх бүрд 10-20 секунд авдаг байв.
#   * Суурь өгөгдөл ба 6,400 барааны импорт хэдэн минут авдаг тул арын
#     дэвсгэрт явж, сервер шууд асна.
set -e

node dist/prisma/sync-schema.js

node dist/prisma/bootstrap.js &

exec node dist/src/main.js
